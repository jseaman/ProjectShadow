function fonts.printList()
	print("Printing all font names")
	
	local fontNames = native.getFontNames()
	for i, fontName in ipairs(fontNames) do
		print(fontName)
	end
	
	print("Done.")
end

-----------------------------------------------------------------------------------------

function fonts.printSimilar(name)
	print("Printing fonts similar to:", name)
	name = name:lower()
	
	local fontNames = native.getFontNames()
	for i, fontName in ipairs(fontNames) do
		local j, k = string.find(fontName:lower(), name)
		if j ~= nil then
			print(fontName)
		end
	end
	print("Done.")
end

-----------------------------------------------------------------------------------------

function fonts.find(name)
	name = name:lower()
	
	local fontNames = native.getFontNames()
	for i, fontName in ipairs(fontNames) do
		local j, k = string.find(fontName:lower(), name)
		if j ~= nil then
			return fontName
		end
	end
	
	return nil
end

-----------------------------------------------------------------------------------------

function fonts.getCorrectName(ios, android, win, winPhone)
	local platform = system.getInfo("platformName")
	if platform == "Win" then
    return win
	elseif platform == "Android" then
    return android
	elseif platform == "WinPhone" then
		return winPhone
	else
		return ios
	end
end

-----------------------------------------------------------------------------------------

function fonts.getFontBySetName(setName)
	return fonts.presets[setName]
end

