-----------------------------------------------------------------------------------------

local puzzles = {}

-----------------------------------------------------------------------------------------

function puzzles.hasFinished(puzzle)
	local game = require("api.game")
	return game.state.isSet("puzzle." .. puzzle)
end

-----------------------------------------------------------------------------------------

function puzzles.finish(puzzle)
	local game = require("api.game")
	game.state.set("puzzle." .. puzzle)
end

-----------------------------------------------------------------------------------------

return puzzles

